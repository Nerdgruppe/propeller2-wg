#!/usr/bin/env python3
"""Freeze measured divided-clock phase profiles and independent validation edges; offline only."""

import bisect
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "captures/physical/2026-10-18/pll-100ms"


def edges(case):
    """Read clock rising edges from immutable Saleae evidence with its selected-source marker."""
    path = DATA / case
    a = json.loads((path / "analysis.json").read_text())
    values, previous = [], None
    for row in csv.DictReader((path / "digital.csv").open()):
        current = int(row["Channel 0"])
        if previous == 0 and current:
            values.append(
                float(row["Time [s]"]) - a["selection_from_trigger_us"] * 1e-6
            )
        previous = current
    return a, values


def phase(values, t, divider):
    """Interpolate cumulative system cycles between independently sampled rising edges."""
    i = bisect.bisect_right(values, t) - 1
    if not 0 <= i < len(values) - 1:
        raise ValueError("Requested profile exceeds the retained record")
    return divider * (i + (t - values[i]) / (values[i + 1] - values[i]))


def main():
    """Write dependency-free Zig profiles and compact train/control vectors with source hashes."""
    output = [
        "//! Generated by utility/gen_clock_profiles.py from accepted 100 MS/s captures.",
        "//! Values integrate normalized frequency; 0.5/1 us piecewise phase interpolation is empirical, not silicon jitter.",
        "pub const Curve = struct { ready: f64, step: f64, phase: []const f64 };",
    ]
    cases = [
        ("m_up", "M-up-r1", 80),
        ("m_down", "M-down-r1", 80),
        ("d_down", "D-only-r1", 80),
        ("cold", "startup-cold-w0-r2", 1000),
        ("warm", "startup-warm-w0-r1", 64),
        ("xi", "startup-xi-nco-cold-r1", 1000),
    ]
    vectors = []
    for name, case, duration in cases:
        a, values = edges(case)
        startup = a["constants"]["FROM_MODE"] == 0
        ready = next(t for t in values if t > 0) if startup else 0
        origin = phase(values, ready, a["pwm_divider"])
        initial = 0 if startup else a["initial"]["hz"]
        target = a["final"]["hz"]
        samples = []
        step = 1.0 if startup else 0.5
        for index in range(round(duration / step) + 1):
            t = index * step * 1e-6
            if t <= ready:
                samples.append(0.0)
            else:
                cycles = phase(values, t, a["pwm_divider"]) - origin
                samples.append((cycles - initial * (t - ready)) / (target - initial))
        digest = hashlib.sha256((DATA / case / "digital.csv").read_bytes()).hexdigest()
        output += [
            f"// {case}; digital.csv SHA256 {digest}",
            f"pub const {name}: Curve = .{{ .ready = {ready:.12g}, .step = {step * 1e-6:.12g}, .phase = &.{{",
        ]
        for index in range(0, len(samples), 6):
            output.append(
                "    "
                + ", ".join(
                    f"{x:.14g}" if x else "0" for x in samples[index : index + 6]
                )
                + ","
            )
        output.append("} };")
        if not startup:
            for suffix in ("r1", "r2", "div8-r1"):
                control = case.rsplit("-", 1)[0] + "-" + suffix
                ca, ce = edges(control)
                selected = [t for t in ce if -2e-6 <= t <= 80e-6]
                vectors.append(
                    {
                        "case": control,
                        "curve": name,
                        "divider": ca["pwm_divider"],
                        "initial": ca["initial"]["hz"],
                        "final": ca["final"]["hz"],
                        "edge_ns": [round(t * 1e9) for t in selected],
                        "csv_sha256": ca["sha256"]["digital.csv"],
                    }
                )
    (ROOT / "src/windtunnel/sim/clock_profiles.zig").write_text(
        "\n".join(output) + "\n"
    )
    (ROOT / "tests/windtunnel/clock-vectors.json").write_text(
        json.dumps(vectors, separators=(",", ":")) + "\n"
    )
    print("froze six measured profiles and nine independent train/control edge records")


if __name__ == "__main__":
    main()
